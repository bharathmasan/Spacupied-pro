export function formatIndianCurrency(amount: number, listingType: 'Rent' | 'Lease'): string {
  if (listingType === 'Rent') {
    return `₹${amount.toLocaleString('en-IN')} / month`;
  }
  if (amount >= 10000000) {
    const cr = amount / 10000000;
    return `₹${Number.isInteger(cr) ? cr : cr.toFixed(2)} Cr lease`;
  }
  if (amount >= 100000) {
    const lakhs = amount / 100000;
    return `₹${Number.isInteger(lakhs) ? lakhs : lakhs.toFixed(1)} Lakhs lease`;
  }
  return `₹${amount.toLocaleString('en-IN')} lease`;
}
